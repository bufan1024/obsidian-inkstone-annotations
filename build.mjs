import { readFile, writeFile } from 'node:fs/promises';

const read = path => readFile(new URL(path, import.meta.url), 'utf8');
const [core, editor, views, menu, i18n, excerpts, plugin, markings, ui, manifest] = await Promise.all([
  read('./src/core.cjs'), read('./src/editor.cjs'), read('./src/views.cjs'), read('./src/annotation-menu.cjs'), read('./src/i18n.cjs'), read('./src/excerpts.cjs'), read('./src/plugin.cjs'), read('./src/markings.css'),
  read('./src/ui.css'), read('./manifest.json')
]);
const bundle = (name, source) => `const ${name} = (() => { const module = { exports: {} };\n${source}\nreturn module.exports; })();\n`;
const main = `/* Inkstone Annotations ${JSON.parse(manifest).version}. MIT License. Generated by build.mjs. */\n` +
  bundle('annotationCore', core) + bundle('annotationEditor', editor) + bundle('annotationViews', views) + bundle('annotationMenu', menu) + bundle('annotationI18n', i18n) + bundle('annotationExcerpts', excerpts) + plugin;
await Promise.all([
  writeFile(new URL('./main.js', import.meta.url), main),
  writeFile(new URL('./styles.css', import.meta.url), markings + '\n' + ui)
]);
console.log('Built the standalone annotation plugin.');
