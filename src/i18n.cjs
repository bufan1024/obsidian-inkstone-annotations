function translate(language = 'zh', source = '', params = {}) {
  const message = language === 'en' && Object.hasOwn(ENGLISH, source) ? ENGLISH[source] : source;
  return message.replace(/\{(\w+)\}/g, (placeholder, name) => params && Object.hasOwn(params, name) ? String(params[name]) : placeholder);
}

